"""pytest integration.

``pytest --plainly``                 print every check as an English sentence
``pytest --plainly-md SPEC.md``      write the spec as Markdown, meant to be committed
``pytest --plainly-check SPEC.md``   fail if the committed spec is out of date
"""
from __future__ import annotations

from collections import Counter, OrderedDict

from . import recorder, subjects


def pytest_addoption(parser):
    group = parser.getgroup("plainly")
    group.addoption("--plainly", action="store_true", help="print checks as a plain-English spec")
    group.addoption("--plainly-md", metavar="PATH", help="write the spec as Markdown to PATH")
    group.addoption("--plainly-check", metavar="PATH", help="fail if PATH differs from the current spec")
    group.addoption("--plainly-width", type=int, default=None, metavar="N",
                    help="longest value shown in a sentence before it is cut off (default 100)")


def pytest_configure(config):
    config._plainly_specs = OrderedDict()
    subjects.WIDTH = config.getoption("--plainly-width") or subjects.DEFAULT_WIDTH


def pytest_unconfigure(config):
    subjects.WIDTH = subjects.DEFAULT_WIDTH  # one run's --plainly-width must not leak into the next


def pytest_runtest_setup(item):
    recorder.drain()


def pytest_runtest_teardown(item):
    records = recorder.drain()
    if records:
        item.config._plainly_specs[item.nodeid] = records


def _title(test_name: str) -> str:
    text = test_name.partition("[")[0]
    if text.startswith("test_"):
        text = text[5:]
    return text.replace("_", " ").capitalize()


EACH = "⟨each⟩"


def _entries(specs):
    """(file, test name, parameter ids, records) in run order."""
    for nodeid, records in specs.items():
        path, _, test = nodeid.partition("::")
        name, _, param = test.split("::")[-1].partition("[")
        yield path, name, [p for p in param.rstrip("]").split("-") if p], records


def _normalised(records, params):
    out = []
    for r in records:
        sentence = r.sentence
        for p in sorted(params, key=len, reverse=True):
            sentence = sentence.replace(p, EACH)
        out.append((sentence, r.passed, r.prose))
    return out


PROSE = " ✎"
LEGEND = (
    "✎ marks wording the test author wrote by hand (a label, `says=`, `name=`, `show=`, `described_as=` or an adapter) "
    "instead of wording derived from the code. Check that it says what the code does."
)


def _line(sentence, passed, prose):
    mark = PROSE if prose else ""
    return f"- {sentence}{mark}" if passed else f"- ✗ FAILED: {sentence}{mark}"


def _bullets(records):
    return [_line(r.sentence, r.passed, r.prose) for r in records]


def cut_off(specs):
    """Sentences that were cut short: the reader cannot see the whole value, so nobody can review them."""
    return [(nodeid, r.sentence) for nodeid, records in specs.items() for r in records if subjects.CUT in r.sentence]


def render_markdown(specs) -> str:
    """Deterministic Markdown: one heading per test, one bullet per check. Git diffs read as sentences.

    A test that runs once per parameter (a rule shared by many classes, say) is written once, with
    ``⟨each⟩`` where the parameter shows up, when every run tells the same story.
    """
    lines = ["<!-- Generated by `pytest --plainly-md`. Review this file: it is the spec. -->", ""]
    handwritten = [r for records in specs.values() for r in records if r.prose]
    if handwritten:
        lines += [f"> {LEGEND}", ">", f"> Wording to review once, covering {len(handwritten)} sentences:"]
        wordings = Counter((r.prose, r.where) for r in handwritten)
        lines += [f"> - {prose}: {where or '(no detail)'} ({n} sentence{'s' if n != 1 else ''})" for (prose, where), n in wordings.items()]
        lines.append("")
    current_file = None
    entries = list(_entries(specs))
    i = 0
    while i < len(entries):
        path, name, params, records = entries[i]
        j = i
        while j < len(entries) and entries[j][0] == path and entries[j][1] == name:
            j += 1
        group = entries[i:j]
        i = j
        if path != current_file:
            lines += [f"## {path}", ""]
            current_file = path
        stories = [_normalised(g[3], g[2]) for g in group]
        if len(group) > 1 and all(g[2] for g in group) and all(s == stories[0] for s in stories):
            values = list(dict.fromkeys(p for g in group for p in g[2]))
            lines += [f"### {_title(name)}", "", f"_Runs for each of: {', '.join(values)}._", ""]
            lines += [_line(s, ok, prose) for s, ok, prose in stories[0]] + [""]
        else:
            for g in group:
                suffix = f" [{'-'.join(g[2])}]" if g[2] else ""
                lines += [f"### {_title(g[1])}{suffix}", ""] + _bullets(g[3]) + [""]
    return "\n".join(lines).rstrip() + "\n"


def pytest_terminal_summary(terminalreporter, config):
    if not config.getoption("--plainly"):
        return
    terminalreporter.section("plain-English spec")
    for nodeid, records in config._plainly_specs.items():
        terminalreporter.write_line(nodeid.replace("::", " > "))
        for r in records:
            terminalreporter.write_line(f"  {'✓' if r.passed else '✗'} {r.sentence}{PROSE if r.prose else ''}")


def pytest_sessionfinish(session, exitstatus):
    config = session.config
    write_to, check = config.getoption("--plainly-md"), config.getoption("--plainly-check")
    if not (write_to or check) or int(exitstatus) != 0:
        return  # never snapshot or judge a failing run
    reporter = config.pluginmanager.get_plugin("terminalreporter")
    cut = cut_off(config._plainly_specs)
    if cut:
        if reporter:
            reporter.write_line(
                f"plainly: {len(cut)} sentence(s) were cut off at {subjects.WIDTH} characters, so a reviewer cannot read them. "
                "Show the value in a shorter form (a smaller example, `show=`, or a label), or raise --plainly-width:",
                red=True,
            )
            for nodeid, sentence in cut[:10]:
                reporter.write_line(f"  {nodeid}: {sentence}")
        session.exitstatus = 1
        return
    text = render_markdown(config._plainly_specs)
    if write_to:
        with open(write_to, "w", encoding="utf-8") as f:
            f.write(text)
    if check:
        try:
            with open(check, encoding="utf-8") as f:
                committed = f.read()
        except FileNotFoundError:
            committed = None
        if committed != text:
            if reporter:
                reporter.write_line(
                    f"plainly: {check} is out of date. Run `pytest --plainly-md {check}` and commit it.",
                    red=True,
                )
            session.exitstatus = 1
